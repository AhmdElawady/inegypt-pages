// Copy self-hosted fonts (all SIL OFL 1.1) from @fontsource and write their @font-face rules (Plan 47 §2.4, D7).
// font-faces.css     production faces: Rubik Latin + Arabic (headings; D20 picked 2026-11-16), IBM Plex Sans Arabic (Arabic body)
// font-faces-dev.css the other candidates, for /dev/type.html only: Nunito, M PLUS Rounded 1c, Readex Pro
// Each web font gets a metric-matched local fallback, so the swap does not shift the layout.
import fs from "node:fs";
const NM = "node_modules";
const OUT = "src/assets/fonts";
fs.mkdirSync(OUT, { recursive: true });

function range(pkgCss, marker) {
  const css = fs.readFileSync(`${NM}/${pkgCss}`, "utf8");
  const block = css.split("/* ").find((b) => b.startsWith(marker + " */"));
  if (!block) throw new Error(`no ${marker} in ${pkgCss}`);
  return block.match(/unicode-range:\s*([^;]+);/)[1];
}
async function metrics(name) { return (await import(`@capsizecss/metrics/${name}`)).default; }

async function fallback(family, metricName, localFonts, refName = "arial") {
  const m = await metrics(metricName), ref = await metrics(refName);
  const sizeAdjust = (m.xWidthAvg / m.unitsPerEm) / (ref.xWidthAvg / ref.unitsPerEm);
  const pct = (v) => `${((v / m.unitsPerEm / sizeAdjust) * 100).toFixed(2)}%`;
  return `@font-face { font-family: "${family} Fallback"; src: ${localFonts.map((f) => `local("${f}")`).join(", ")};
  size-adjust: ${(sizeAdjust * 100).toFixed(2)}%; ascent-override: ${pct(m.ascent)}; descent-override: ${pct(Math.abs(m.descent))}; line-gap-override: ${pct(m.lineGap)}; }\n`;
}

const faces = [
  // [family, package dir, file, weight, css file for the range, marker, dev only, metric name, local fallbacks]
  ["Rubik", "@fontsource-variable/rubik", "rubik-latin-wght-normal.woff2", "300 900", "wght.css", "rubik-latin-wght-normal", false, "rubik", ["Arial", "Helvetica"]],
  ["Rubik", "@fontsource-variable/rubik", "rubik-arabic-wght-normal.woff2", "300 900", "wght.css", "rubik-arabic-wght-normal", false, null],
  ["Nunito", "@fontsource-variable/nunito", "nunito-latin-wght-normal.woff2", "200 1000", "wght.css", "nunito-latin-wght-normal", true, null],
  ["IBM Plex Sans Arabic", "@fontsource/ibm-plex-sans-arabic", "ibm-plex-sans-arabic-arabic-400-normal.woff2", "400", "400.css", "ibm-plex-sans-arabic-arabic-400-normal", false, null],
  ["IBM Plex Sans Arabic", "@fontsource/ibm-plex-sans-arabic", "ibm-plex-sans-arabic-arabic-700-normal.woff2", "700", "700.css", "ibm-plex-sans-arabic-arabic-700-normal", false, null],
  ["M PLUS Rounded 1c", "@fontsource/m-plus-rounded-1c", "m-plus-rounded-1c-latin-800-normal.woff2", "800", "800.css", "m-plus-rounded-1c-latin-800-normal", true, null],
  ["M PLUS Rounded 1c", "@fontsource/m-plus-rounded-1c", "m-plus-rounded-1c-latin-700-normal.woff2", "700", "700.css", "m-plus-rounded-1c-latin-700-normal", true, null],
  ["Readex Pro", "@fontsource-variable/readex-pro", "readex-pro-arabic-wght-normal.woff2", "160 700", "wght.css", "readex-pro-arabic-wght-normal", true, null],
];

let prod = "/* Generated by scripts/copy-fonts.mjs. Fonts: SIL Open Font License 1.1 (via @fontsource). */\n";
let dev = prod;
let bytes = 0;
for (const [family, pkg, file, weight, css, marker, devOnly, metricName, locals] of faces) {
  fs.copyFileSync(`${NM}/${pkg}/files/${file}`, `${OUT}/${file}`);
  const size = fs.statSync(`${OUT}/${file}`).size;
  if (!devOnly) bytes += size;
  const rule = `@font-face { font-family: "${family}"; font-style: normal; font-display: swap; font-weight: ${weight};
  src: url("../fonts/${file}") format("woff2"); unicode-range: ${range(`${pkg}/${css}`, marker)}; }\n`;
  if (devOnly) dev += rule; else prod += rule;
  if (metricName) prod += await fallback(family, metricName, locals);
}
fs.writeFileSync("src/_includes/css/font-faces.css", prod);
fs.writeFileSync("src/_includes/css/font-faces-dev.css", dev);
console.log(`fonts: production files ${(bytes / 1024).toFixed(0)} KB total (each loads only when its glyphs are used)`);
